"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const script = fs.readFileSync(path.join(__dirname, "../public/js/ppic-mps-workbench.js"), "utf8");
const start = script.indexOf("  const assessmentMeta =");
const end = script.indexOf("  const leadTime =", start);
assert(start > 0 && end > start);
const context = vm.createContext({ num: String, esc: (value) => String(value).replaceAll("<", "&lt;").replaceAll('"', "&quot;") });
vm.runInContext(script.slice(start, end), context);
const render = (input) => vm.runInContext(`checklistCell(${JSON.stringify(input)})`, context);
const summary = { lineId: "L1", status: "NOT_EVALUATED", checkedCount: 12, totalCount: 12, okCount: 7, failCount: 1, warningCount: 1, notCheckedCount: 3 };
const html = render(summary);
assert.match(html, /12\/12 diperiksa/);
assert.match(html, /7 lolos · 1 gagal · 1 risiko · 3 data kurang/);
assert.doesNotMatch(html, /12\/12 OK/);
assert.match(render({ ...summary, checkedCount: undefined }), /7\/12 lolos/, "old API response must not fabricate full check progress");
assert.match(render({ ...summary, lineId: '<"evil' }), /data-feasibility-line="&lt;&quot;evil"/);
console.log("MPS checklist progress: inspected vs passed vs missing data and legacy fallback PASS");
