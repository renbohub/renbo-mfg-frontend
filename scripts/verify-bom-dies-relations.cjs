const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const window = {};
const context = vm.createContext({ window });
for (const file of ['bom-machine-policy.js', 'bom-executor-policy.js']) {
  vm.runInContext(fs.readFileSync(path.join(__dirname, '../public/js', file), 'utf8'), context);
}
const policy = window.BomMachinePolicy;
const machines = [{ id: 'P1', machineCode: 'P1', status: 'Active', machineSpecificationCode: 'PRESS' }];
const die = (id, partId, extra = {}) => ({ id, diesCode: id, diesName: id, status: 'Active', diesParts: [{ partId, isActive: true }], ...extra });
const dies = [die('correct', 'child'), die('other', 'other-child'), die('fg-die', 'fg'), die('inactive-link', 'child', { diesParts: [{ partId: 'child', isActive: false }] }), die('retired', 'child', { status: 'Retired' }), die('deleted', 'child', { isDeleted: true }), die('no-link', null, { diesParts: [] }), die('shared', 'child', { diesParts: [{ partId: 'child', isActive: true }, { partId: 'other-child', isActive: true }] })];
const route = { routingMode: 'INHOUSE', machineSpecificationCode: 'PRESS', cycleTime: 6, diesId: 'correct', machinePlanningPolicy: { primaryMachineId: 'P1', resources: [{ machineId: 'P1', diesId: 'correct', cycleTimeSeconds: 6 }] } };
assert.deepEqual(Array.from(policy.eligibleDies(dies, 'child'), d => d.id), ['correct', 'shared']);
assert.equal(policy.eligibleDies(dies, null).length, 0);
const html = policy.render(route, machines, dies, 'child');
for (const id of ['correct', 'shared']) assert(html.includes(`value="${id}"`));
for (const id of ['other', 'fg-die', 'inactive-link', 'retired', 'deleted', 'no-link']) assert(!html.includes(`value="${id}"`), `${id} must not be offered`);
assert.match(policy.render(route, machines, [], 'child'), /Belum ada relasi dies aktif/);
assert.match(policy.render(route, machines, dies, 'new-child'), /selected disabled>Dies tersimpan tidak sesuai/);
const vendor = { routingMode: 'VENDOR', vendorId: 'v', machinePlanningPolicy: { execution: { allowedModes: ['VENDOR', 'INHOUSE'], inhouse: structuredClone(route) } } };
const alternateHtml = window.BomExecutorPolicy.render(vendor, machines, dies, [{ id: 'v', vendorCode: 'V' }], 'child');
assert(alternateHtml.includes('value="correct"'));
assert(!alternateHtml.includes('value="other"'));
const switched = structuredClone(route);
switched.machinePlanningPolicy.resources.push({ machineId: 'P2', diesId: 'shared' });
switched.machinePlanningPolicy.execution = structuredClone(vendor.machinePlanningPolicy.execution);
policy.clearUnrelatedDies(switched, dies, 'other-child');
assert.equal(switched.diesId, null);
assert.equal(switched.machinePlanningPolicy.resources[0].diesId, null);
assert.equal(switched.machinePlanningPolicy.resources[1].diesId, 'shared');
assert.equal(switched.machinePlanningPolicy.execution.inhouse.diesId, null);
assert.equal(switched.machinePlanningPolicy.execution.inhouse.machinePlanningPolicy.resources[0].diesId, null);
assert.equal(switched.cycleTime, 6, 'Changing part does not alter cycle time');
const edited = structuredClone(route);
policy.update(edited, { dataset: { policyField: 'diesId', policyMachine: 'P1' }, value: 'shared' });
assert.equal(edited.diesId, 'shared');
assert.equal(edited.machinePlanningPolicy.resources[0].diesId, 'shared');
policy.update(edited, { dataset: { policyField: 'diesId', policyMachine: 'P1' }, value: '' });
assert.equal(edited.diesId, null);
assert.equal(edited.machinePlanningPolicy.resources[0].diesId, null);
console.log('PASS: child-specific dies, active relations, shared dies, empty/stale selections, alternative tooling, part switching and primary-tool synchronization.');
