"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const model = require("../public/js/ppic-mrp-supply-model");
const supplied = { materialSupplyType: "CUSTOMER_SUPPLIED", supplyCustomerCode: "C003", netRequirement: 120, plannedOrderQtyPcs: 0 };
assert.equal(model.matrixQty(supplied, { netQty: 120, discrete: true, lookahead: false }), 120, "zero purchase orders must not hide physical customer supply requirements");
assert.equal(model.matrixQty(supplied, { netQty: 12.5, discrete: false, lookahead: false }), 12.5);
assert.equal(model.matrixQty(supplied, { netQty: 0, discrete: true, lookahead: false }), 0, "covered is not fabricated demand");
assert.equal(model.supplyLabel(supplied), "Disuplai customer C003");
assert.notEqual(model.supplyKey(supplied), model.supplyKey({ materialSupplyType: "SUPPLIER_PURCHASE" }));
assert.notEqual(model.supplyKey(supplied), model.supplyKey({ ...supplied, supplyCustomerCode: "C004" }));
assert.equal(model.isCustomerSupplied({ mbomDetail: supplied }), false, "do not reclassify historical runs with a live BOM edit");
assert.equal(model.matrixQty({ plannedOrderQtyPcs: 4 }, { netQty: 3.5, discrete: true, lookahead: false }), 4);
assert.equal(model.matrixQty({ plannedOrderQtyPcs: 4 }, { netQty: 3.5, discrete: true, lookahead: true }), 3.5);
const script = fs.readFileSync(require.resolve("../public/js/ppic-mrp-detail-simple.js"), "utf8");
assert.match(script, /Menunggu suplai customer/);
assert.match(script, /Suplai customer · tidak dibeli/);
assert.match(script, /supplyModel\.supplyKey\(item\)/);
assert.match(script, /activeBuy = buy\.filter\(\(row\) => row\._state\.key !== "COVERED" && !supplyModel\.isCustomerSupplied\(row\)\)/);
console.log("MRP supplied materials: visible net qty, no false purchasing KPI, supply identity separation, covered and lookahead PASS");
