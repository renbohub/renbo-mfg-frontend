"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const window = {};
const context = vm.createContext({ window });
for (const file of ["bom-machine-policy.js", "bom-executor-policy.js"]) vm.runInContext(fs.readFileSync(path.join(__dirname, "../public/js", file), "utf8"), context);
const api = window.BomExecutorPolicy;
const value = row => JSON.parse(JSON.stringify(row));
const route = { routingMode: "INHOUSE", machineSpecificationCode: "PRESS", cycleTime: 6, diesId: "d", machinePlanningPolicy: { primaryMachineId: "m", mode: "SINGLE", resources: [{ machineId: "m", diesId: "d", cycleTimeSeconds: 6 }] } };
const target = (field, checked, extra = {}) => ({ dataset: { executionField: field, ...extra }, checked });
assert.match(api.render(route, [], [], []), /Izinkan vendor sebagai alternatif/);
assert.equal(route.machinePlanningPolicy.execution, undefined, "render must not grant permissions");
api.update(route, target("allowAlternative", true));
api.update(route, target("allowSplit", true));
api.update(route, target("vendorId", true, { executionVendor: "v" }));
api.changeDefault(route, "VENDOR");
assert.equal(route.cycleTime, 0);
assert.equal(route.machinePlanningPolicy.execution.inhouse.cycleTime, 6);
assert.equal(route.machinePlanningPolicy.execution.inhouse.machinePlanningPolicy.primaryMachineId, "m");
assert.match(api.render(route, [{ id: "m", machineCode: "M", status: "Active", machineSpecificationCode: "PRESS" }], [], [{ id: "v", vendorCode: "V", vendorName: "Bintang" }]), /data-executor-inhouse/);
const nested = { dataset: { policyField: "cycleTimeSeconds", policyMachine: "m" }, value: "9", closest: () => ({}) };
api.update(route, nested);
assert.equal(route.machinePlanningPolicy.execution.inhouse.machinePlanningPolicy.resources[0].cycleTimeSeconds, 9);
assert.equal(route.machinePlanningPolicy.resources, undefined, "nested changes must not leak into vendor default");
api.changeDefault(route, "INHOUSE");
assert.equal(route.cycleTime, 6);
assert.equal(route.machinePlanningPolicy.resources[0].cycleTimeSeconds, 9);
assert.deepEqual(value(route.machinePlanningPolicy.execution.vendorIds), ["v"]);
api.resetMachines(route);
assert.deepEqual(value(route.machinePlanningPolicy.execution.vendorIds), ["v"], "specification reset must preserve executor permission");
api.update(route, target("allowAlternative", false));
assert.deepEqual(value(route.machinePlanningPolicy.execution.allowedModes), ["INHOUSE"]);
assert.equal(route.machinePlanningPolicy.execution.allowSplit, false);
const vendorOnly = { routingMode: "VENDOR", vendorId: "v", machinePlanningPolicy: {} };
api.changeDefault(vendorOnly, "INHOUSE");
assert.deepEqual(value(vendorOnly.machinePlanningPolicy.execution.allowedModes), ["INHOUSE"], "default change does not grant dual execution");
console.log("PASS: BOM executor UI permissions, reversible defaults, nested tooling state, split reset and machine-policy preservation");
